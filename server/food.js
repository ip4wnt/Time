// Единицы измерения -> граммы (или мл для жидкостей)
const UNITS = [
  [/^(кг|килограмм\w*)$/, (n) => n * 1000, 'g'],
  [/^(г|гр|грамм\w*|g)$/, (n) => n, 'g'],
  [/^(мл|миллилитр\w*|ml)$/, (n) => n, 'ml'],
  [/^(л|литр\w*|l)$/, (n) => n * 1000, 'ml'],
  [/^(шт|штук\w*|штуки|штука|pcs)$/, (n) => n, 'pc'],
  [/^(ст\.?л\.?|столов\w*|ложк\w*)$/, (n) => n * 15, 'g'],
  [/^(ч\.?л\.?|чайн\w*)$/, (n) => n * 5, 'g'],
  [/^(стакан\w*|ст\.)$/, (n) => n * 250, 'ml'],
  [/^(кружк\w*|чашк\w*)$/, (n) => n * 250, 'ml'],
  [/^(ломтик\w*|кусоч\w*|кусок|куска|кусков)$/, (n) => n, 'pc'],
  [/^(порци\w*|тарелк\w*)$/, (n) => n, 'portion'],
  [/^(банк\w*|бутылк\w*)$/, (n) => n * 330, 'ml'],
];

function norm(s) {
  return s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9.,\s/]/g, ' ').replace(/\s+/g, ' ').trim();
}

function stem(w) {
  // грубое усечение русских окончаний, чтобы «яблоки» ≈ «яблоко»
  return w.replace(/(ами|ями|ов|ев|ей|ой|ою|ий|ый|ая|яя|ое|ее|ие|ые|ую|юю|ам|ям|ах|ях|ом|ем|а|я|о|е|ы|и|у|ю|ь)$/u, '');
}

const STOP = /^(и|с|со|из|на|в|по|под|без|для)$/;
const INDEX = DB.map((row) => {
  const [keys, kcal, p, f, c, piece = null, note = null, density = null] = row;
  const variants = keys.split('|').map((k) => ({ label: k, words: norm(k).split(' ').filter((w) => !STOP.test(w)).map(stem).filter(Boolean) }));
  return { label: variants[0].label, variants, kcal, p, f, c, piece, note, density };
});

function matchProduct(words) {
  const stems = words.map(stem);
  let best = null;
  for (const prod of INDEX) {
    for (const v of prod.variants) {
      // все слова варианта должны встречаться среди слов записи
      let exact = 0, ok = true;
      for (const vw of v.words) {
        if (stems.some((s) => s === vw)) { exact++; continue; }
        if (stems.some((s) => vw.length >= 4 && (s.startsWith(vw) || vw.startsWith(s)))) continue;
        ok = false; break;
      }
      if (!ok) continue;
      // Точное совпадение основы важнее длины: иначе «слива» подтягивает «сливки»,
      // потому что основа «сливк» длиннее и начинается на «слив».
      const score = v.words.length * 1000 + exact * 100 + v.words.join('').length;
      if (!best || score > best.score) best = { prod, score, variant: v.label };
    }
  }
  return best;
}

// «120 ккал/100 г», «120ккал на 100г» — калорийность с упаковки.
const PER100_RE = /(\d+(?:[.,]\d+)?)\s*(?:ккал|кал)\s*(?:\/|на)\s*(\d+(?:[.,]\d+)?)\s*(?:грамм\w*|гр|г|мл)(?![a-zа-я])/i;
// «38x5г», «38 х 5 г», «2*150г» — количество штук на вес одной.
const MULT_RE = /(\d+(?:[.,]\d+)?)\s*[xх×*]\s*(\d+(?:[.,]\d+)?)/i;

function parseItem(raw) {
  let src = String(raw);
  const num = (s) => parseFloat(String(s).replace(',', '.'));

  // Калорийность на 100 г вырезаем до общего разбора, иначе числа из неё уйдут в вес.
  let per100Kcal = null;
  const per100 = src.match(PER100_RE);
  if (per100) {
    const base = num(per100[2]);
    if (base > 0) per100Kcal = num(per100[1]) * (100 / base);
    src = src.replace(per100[0], ' ');
  }

  // Множитель: 38x5г → 190 г.
  let multNote = null;
  const mult = src.match(MULT_RE);
  if (mult) {
    const a = num(mult[1]), b = num(mult[2]);
    const res = Math.round(a * b * 100) / 100;
    multNote = `${a} × ${b} = ${res}`;
    src = src.replace(mult[0], String(res));
  }

  const text = norm(src);
  if (!text) return null;
  const tokens = text.split(' ');
  let qty = null, unit = null, explicitKcal = null;
  const words = [];
  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i];
    const numMatch = t.match(/^(\d+(?:[.,]\d+)?)([a-zа-я.]*)$/);
    if (numMatch) {
      const n = parseFloat(numMatch[1].replace(',', '.'));
      let u = numMatch[2] || tokens[i + 1] || '';
      let consumedNext = !numMatch[2] && !!tokens[i + 1];
      if (/^ккал|кал\w*$/.test(u)) { explicitKcal = n; if (consumedNext) i++; continue; }
      let found = null;
      for (const [re, fn, kind] of UNITS) if (re.test(u)) { found = { grams: fn(n), kind }; break; }
      if (found) { qty = found; if (consumedNext) i++; continue; }
      if (!numMatch[2] && qty === null) {
        // число без единиц: перед названием и небольшое — штуки, иначе граммы
        if (words.length === 0 && n <= 20) qty = { grams: n, kind: 'pc', assumed: true };
        else qty = { grams: n, kind: 'g', assumed: true };
        continue;
      }
      if (numMatch[2]) { words.push(t); continue; }
      continue;
    }
    if (/^(и|с|со|из|на|в|по|под|без|для|одна|один|одно|пара|пару|немного|чуть|около|примерно|штука|штуки)$/.test(t)) {
      if (/^(одна|один|одно)$/.test(t)) qty = qty || { grams: 1, kind: 'pc' };
      if (/^(пара|пару)$/.test(t)) qty = qty || { grams: 2, kind: 'pc' };
      continue;
    }
    if (/^(половина|половину|пол)$/.test(t)) { qty = qty || { grams: 0.5, kind: 'pc' }; continue; }
    words.push(t);
  }
  return { raw: String(raw).trim(), words, qty, explicitKcal, per100Kcal, multNote };
}

function calcItem(item) {
  const m = matchProduct(item.words);
  const out = { input: item.raw, product: null, grams: null, kcal: 0, protein: 0, fat: 0, carbs: 0, note: '' };
  if (!m) {
    if (item.per100Kcal != null) {
      const g = item.qty && item.qty.kind === 'g' ? item.qty.grams : 100;
      out.product = item.words.join(' ') || 'продукт';
      out.grams = Math.round(g);
      out.kcal = Math.round(item.per100Kcal * g / 100);
      out.note = `продукт не распознан, считали по ${Math.round(item.per100Kcal)} ккал/100 г`;
    } else if (item.explicitKcal != null) {
      out.kcal = item.explicitKcal; out.product = item.words.join(' ') || 'продукт'; out.note = 'продукт не распознан, взяты указанные ккал';
    } else {
      out.note = 'продукт не распознан';
    }
    if (item.multNote) out.note = `${item.multNote}; ${out.note}`;
    return out;
  }
  const p = m.prod;
  out.product = p.label + (p.note ? ` (${p.note})` : '');
  let grams;
  const q = item.qty;
  if (!q) {
    grams = p.piece || 100;
    out.note = p.piece ? `количество не указано — 1 шт ≈ ${p.piece} г` : 'количество не указано — взято 100 г';
  } else if (q.kind === 'g') {
    grams = q.grams;
    if (q.assumed) out.note = 'число без единиц — принято за граммы';
  } else if (q.kind === 'ml') {
    grams = q.grams * (p.density || 1);
    out.note = `${q.grams} мл × плотность ${p.density || 1}`;
  } else if (q.kind === 'pc') {
    const pw = p.piece || 100;
    grams = q.grams * pw;
    out.note = `${q.grams} шт × ${pw} г${q.assumed ? ' (число перед названием принято за штуки)' : ''}`;
  } else if (q.kind === 'portion') {
    const pw = p.piece || 250;
    grams = q.grams * pw;
    out.note = `${q.grams} порц. × ${pw} г`;
  }
  out.grams = Math.round(grams);
  const k = grams / 100;
  const kcal100 = item.per100Kcal != null ? item.per100Kcal : p.kcal;
  out.kcal = item.explicitKcal != null ? item.explicitKcal : Math.round(kcal100 * k);
  if (item.per100Kcal != null) out.note = (out.note ? out.note + '; ' : '') + `${Math.round(item.per100Kcal)} ккал/100 г из записи`;
  if (item.explicitKcal != null) out.note = (out.note ? out.note + '; ' : '') + 'ккал взяты из записи';
  if (item.multNote) out.note = `${item.multNote}${out.note ? '; ' + out.note : ''}`;
  // КБЖУ — из таблицы; если калорийность задана вручную, масштабируем их пропорционально.
  const adj = item.per100Kcal != null && p.kcal > 0 ? item.per100Kcal / p.kcal : 1;
  out.protein = Math.round(p.p * adj * k * 10) / 10;
  out.fat = Math.round(p.f * adj * k * 10) / 10;
  out.carbs = Math.round(p.c * adj * k * 10) / 10;
  out.per100 = { kcal: Math.round(kcal100), protein: Math.round(p.p * adj * 10) / 10, fat: Math.round(p.f * adj * 10) / 10, carbs: Math.round(p.c * adj * 10) / 10 };
  return out;
}

function calc(text) {
  const parts = String(text || '')
    .split(/\n|;|,(?!\d)|\s\+\s|\sи\s/)
    .map((s) => s.trim())
    .filter(Boolean);
  const items = parts.map(parseItem).filter(Boolean).map(calcItem);
  const total = items.reduce((a, i) => ({
    kcal: a.kcal + (i.kcal || 0), protein: a.protein + (i.protein || 0), fat: a.fat + (i.fat || 0), carbs: a.carbs + (i.carbs || 0),
  }), { kcal: 0, protein: 0, fat: 0, carbs: 0 });
  for (const k of Object.keys(total)) total[k] = Math.round(total[k] * 10) / 10;
  total.kcal = Math.round(total.kcal);
  const unknown = items.filter((i) => !i.product).length;
  return { items, total, unknown };
}

module.exports = { calc };
